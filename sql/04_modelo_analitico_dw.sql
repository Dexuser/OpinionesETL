DROP SCHEMA IF EXISTS dw CASCADE;
CREATE SCHEMA dw;

-- ---------------------------------------------------------------------
-- 1. DIMENSIONES
-- ---------------------------------------------------------------------
CREATE TABLE dw.dim_tiempo (
    id_tiempo        INTEGER      PRIMARY KEY,           -- yyyymmdd, ej. 20250827
    fecha            DATE         NOT NULL UNIQUE,
    anio             SMALLINT     NOT NULL,
    trimestre        SMALLINT     NOT NULL CHECK (trimestre BETWEEN 1 AND 4),
    mes              SMALLINT     NOT NULL CHECK (mes BETWEEN 1 AND 12),
    nombre_mes       VARCHAR(12)  NOT NULL,
    anio_mes         CHAR(7)      NOT NULL,              -- '2025-08'
    anio_trimestre   CHAR(7)      NOT NULL,              -- '2025-T3'
    dia              SMALLINT     NOT NULL,
    dia_semana       SMALLINT     NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),  -- 1 = lunes
    nombre_dia       VARCHAR(12)  NOT NULL,
    es_fin_de_semana BOOLEAN      NOT NULL
);

CREATE TABLE dw.dim_producto (
    sk_producto  INTEGER      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_producto  INTEGER      NOT NULL UNIQUE,           -- clave natural (opiniones.producto)
    nombre       VARCHAR(100) NOT NULL,
    categoria    VARCHAR(50)  NOT NULL                   -- categoría desnormalizada dentro de la dimensión
);

CREATE TABLE dw.dim_cliente (
    sk_cliente   INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente   INTEGER      UNIQUE,                    -- NULL solo en la fila "Anónimo"
    nombre       VARCHAR(100) NOT NULL,
    email        VARCHAR(150),
    -- Atributos de segmentación: los CSV no los traen; quedan listos para cuando existan.
    pais         VARCHAR(50)  NOT NULL DEFAULT 'No disponible',
    rango_edad   VARCHAR(20)  NOT NULL DEFAULT 'No disponible',
    tipo_cliente VARCHAR(30)  NOT NULL DEFAULT 'No disponible'
);

CREATE TABLE dw.dim_fuente (
    sk_fuente    SMALLINT     GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tipo_fuente  VARCHAR(20)  NOT NULL,                  -- Encuesta / Reseña web / Red social
    canal        VARCHAR(30)  NOT NULL,                  -- EncuestaInterna / Web / Instagram / Facebook / Twitter
    CONSTRAINT uq_dim_fuente UNIQUE (tipo_fuente, canal),
    CONSTRAINT ck_dim_fuente_tipo CHECK (tipo_fuente IN ('Encuesta', 'Reseña web', 'Red social'))
);

CREATE TABLE dw.dim_sentimiento (
    sk_sentimiento SMALLINT   PRIMARY KEY,
    nombre         VARCHAR(20) NOT NULL UNIQUE           -- Positiva / Neutra / Negativa / Sin clasificar
);

CREATE TABLE dw.dim_evento (
    sk_evento    INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(100) NOT NULL,
    tipo         VARCHAR(30)  NOT NULL,                  -- Lanzamiento / Campaña / Ninguno
    fecha_inicio DATE,
    fecha_fin    DATE,
    CONSTRAINT ck_dim_evento_fechas CHECK (
        sk_evento = 0 OR (fecha_inicio IS NOT NULL AND fecha_fin IS NOT NULL AND fecha_fin >= fecha_inicio))
);

-- ---------------------------------------------------------------------
-- 2. TABLA DE HECHOS  (grano: una fila por opinión, de cualquier canal)
-- ---------------------------------------------------------------------
CREATE TABLE dw.fact_opinion (
    sk_opinion     BIGINT       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_tiempo      INTEGER      NOT NULL,
    sk_producto    INTEGER      NOT NULL,
    sk_cliente     INTEGER      NOT NULL,                -- 0 = comentario anónimo
    sk_fuente      SMALLINT     NOT NULL,
    sk_sentimiento SMALLINT     NOT NULL,
    sk_evento      INTEGER      NOT NULL DEFAULT 0,      -- 0 = sin evento
    -- dimensión degenerada: identifica la opinión en el sistema transaccional
    origen         VARCHAR(10)  NOT NULL,                -- Encuesta / Web / Social
    id_origen      VARCHAR(20)  NOT NULL,                -- 123 / W0001 / T0007
    -- medidas
    puntaje        SMALLINT,                             -- 1-5; NULL en redes sociales (no tienen puntaje)
    es_positiva    SMALLINT     NOT NULL DEFAULT 0,      -- banderas 0/1: se suman para contar y sacar porcentajes
    es_neutra      SMALLINT     NOT NULL DEFAULT 0,
    es_negativa    SMALLINT     NOT NULL DEFAULT 0,
    comentario     VARCHAR(500) NOT NULL,
    fecha_carga    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_fact_opinion_origen UNIQUE (origen, id_origen),
    CONSTRAINT ck_fact_origen   CHECK (origen IN ('Encuesta', 'Web', 'Social')),
    CONSTRAINT ck_fact_puntaje  CHECK (puntaje IS NULL OR puntaje BETWEEN 1 AND 5),
    CONSTRAINT ck_fact_banderas CHECK (es_positiva + es_neutra + es_negativa <= 1),
    CONSTRAINT fk_fact_tiempo      FOREIGN KEY (id_tiempo)      REFERENCES dw.dim_tiempo (id_tiempo),
    CONSTRAINT fk_fact_producto    FOREIGN KEY (sk_producto)    REFERENCES dw.dim_producto (sk_producto),
    CONSTRAINT fk_fact_cliente     FOREIGN KEY (sk_cliente)     REFERENCES dw.dim_cliente (sk_cliente),
    CONSTRAINT fk_fact_fuente      FOREIGN KEY (sk_fuente)      REFERENCES dw.dim_fuente (sk_fuente),
    CONSTRAINT fk_fact_sentimiento FOREIGN KEY (sk_sentimiento) REFERENCES dw.dim_sentimiento (sk_sentimiento),
    CONSTRAINT fk_fact_evento      FOREIGN KEY (sk_evento)      REFERENCES dw.dim_evento (sk_evento)
);

CREATE INDEX ix_fact_tiempo      ON dw.fact_opinion (id_tiempo);
CREATE INDEX ix_fact_producto    ON dw.fact_opinion (sk_producto);
CREATE INDEX ix_fact_cliente     ON dw.fact_opinion (sk_cliente);
CREATE INDEX ix_fact_fuente      ON dw.fact_opinion (sk_fuente);
CREATE INDEX ix_fact_sentimiento ON dw.fact_opinion (sk_sentimiento);
CREATE INDEX ix_fact_evento      ON dw.fact_opinion (sk_evento);

