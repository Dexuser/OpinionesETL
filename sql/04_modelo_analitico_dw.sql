-- ---------------------------------------------------------------------
-- 4. CARGA DESDE EL ESQUEMA TRANSACCIONAL (opiniones -> dw)
--    Es repetible: las dimensiones se actualizan y los hechos ya cargados se omiten.
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE dw.sp_cargar_dw()
LANGUAGE plpgsql
AS $$
DECLARE
    v_tiempo   INTEGER;
    v_producto INTEGER;
    v_cliente  INTEGER;
    v_hechos   INTEGER;
BEGIN
    -- Calendario: todos los días desde el primer mes hasta el último mes con opiniones
    INSERT INTO dw.dim_tiempo
        (id_tiempo, fecha, anio, trimestre, mes, nombre_mes, anio_mes, anio_trimestre,
         dia, dia_semana, nombre_dia, es_fin_de_semana)
    SELECT to_char(g.d, 'YYYYMMDD')::INTEGER,
           g.d::DATE,
           EXTRACT(YEAR FROM g.d)::SMALLINT,
           EXTRACT(QUARTER FROM g.d)::SMALLINT,
           EXTRACT(MONTH FROM g.d)::SMALLINT,
           (ARRAY['Enero','Febrero','Marzo','Abril','Mayo','Junio','Julio','Agosto',
                  'Septiembre','Octubre','Noviembre','Diciembre'])[EXTRACT(MONTH FROM g.d)::INT],
           to_char(g.d, 'YYYY-MM'),
           to_char(g.d, 'YYYY') || '-T' || EXTRACT(QUARTER FROM g.d)::INT,
           EXTRACT(DAY FROM g.d)::SMALLINT,
           EXTRACT(ISODOW FROM g.d)::SMALLINT,
           (ARRAY['Lunes','Martes','Miércoles','Jueves','Viernes','Sábado','Domingo'])[EXTRACT(ISODOW FROM g.d)::INT],
           EXTRACT(ISODOW FROM g.d) IN (6, 7)
    FROM generate_series(
             (SELECT date_trunc('month', MIN(fecha))::TIMESTAMP FROM opiniones.vw_opiniones_consolidadas),
             (SELECT (date_trunc('month', MAX(fecha)) + INTERVAL '1 month' - INTERVAL '1 day')::TIMESTAMP
                FROM opiniones.vw_opiniones_consolidadas),
             INTERVAL '1 day') AS g(d)
    ON CONFLICT (id_tiempo) DO NOTHING;
    GET DIAGNOSTICS v_tiempo = ROW_COUNT;

    -- Productos (con su categoría incluida)
    INSERT INTO dw.dim_producto (id_producto, nombre, categoria)
    SELECT p.id_producto, p.nombre, c.nombre
      FROM opiniones.producto p
      JOIN opiniones.categoria_producto c ON c.id_categoria = p.id_categoria
    ON CONFLICT (id_producto) DO UPDATE
        SET nombre = EXCLUDED.nombre, categoria = EXCLUDED.categoria;
    GET DIAGNOSTICS v_producto = ROW_COUNT;

    -- Clientes (no se tocan pais / rango_edad / tipo_cliente si ya fueron completados)
    INSERT INTO dw.dim_cliente (id_cliente, nombre, email)
    SELECT id_cliente, nombre, email FROM opiniones.cliente
    ON CONFLICT (id_cliente) DO UPDATE
        SET nombre = EXCLUDED.nombre, email = EXCLUDED.email;
    GET DIAGNOSTICS v_cliente = ROW_COUNT;

    -- Canales nuevos que aparezcan en los datos
    INSERT INTO dw.dim_fuente (tipo_fuente, canal)
    SELECT DISTINCT
           CASE o.origen WHEN 'Encuesta' THEN 'Encuesta' WHEN 'Web' THEN 'Reseña web' ELSE 'Red social' END,
           o.canal
      FROM opiniones.vw_opiniones_consolidadas o
    ON CONFLICT (tipo_fuente, canal) DO NOTHING;

    -- Hechos: una fila por opinión
    INSERT INTO dw.fact_opinion
        (id_tiempo, sk_producto, sk_cliente, sk_fuente, sk_sentimiento, sk_evento,
         origen, id_origen, puntaje, es_positiva, es_neutra, es_negativa, comentario)
    SELECT t.id_tiempo,
           p.sk_producto,
           COALESCE(c.sk_cliente, 0),
           f.sk_fuente,
           COALESCE(s.sk_sentimiento, 0),
           COALESCE(ev.sk_evento, 0),
           o.origen,
           o.id_origen,
           o.puntaje,
           CASE WHEN s.nombre = 'Positiva' THEN 1 ELSE 0 END,
           CASE WHEN s.nombre = 'Neutra'   THEN 1 ELSE 0 END,
           CASE WHEN s.nombre = 'Negativa' THEN 1 ELSE 0 END,
           o.comentario
      FROM opiniones.vw_opiniones_consolidadas o
      JOIN dw.dim_tiempo   t ON t.fecha = o.fecha
      JOIN dw.dim_producto p ON p.id_producto = o.id_producto
      JOIN dw.dim_fuente   f ON f.canal = o.canal
                            AND f.tipo_fuente = CASE o.origen WHEN 'Encuesta' THEN 'Encuesta'
                                                              WHEN 'Web' THEN 'Reseña web' ELSE 'Red social' END
      LEFT JOIN dw.dim_cliente c ON c.id_cliente = o.id_cliente
      LEFT JOIN opiniones.clasificacion_sentimiento cl ON cl.id_clasificacion = o.id_clasificacion
      LEFT JOIN dw.dim_sentimiento s ON s.nombre = cl.nombre
      LEFT JOIN LATERAL (
            SELECT e.sk_evento
              FROM dw.dim_evento e
             WHERE e.sk_evento <> 0 AND o.fecha BETWEEN e.fecha_inicio AND e.fecha_fin
             ORDER BY e.fecha_inicio DESC
             LIMIT 1
      ) ev ON TRUE
    ON CONFLICT (origen, id_origen) DO NOTHING;
    GET DIAGNOSTICS v_hechos = ROW_COUNT;

    RAISE NOTICE 'dw cargado: % días nuevos, % productos, % clientes, % opiniones nuevas',
                 v_tiempo, v_producto, v_cliente, v_hechos;
END;
$$;

-- ---------------------------------------------------------------------
-- 5. VISTAS ANALÍTICAS (cada una responde un grupo de preguntas del enunciado)
-- ---------------------------------------------------------------------
-- Indicadores generales (1.1, 1.2, 1.4, 5.1, 5.3)
CREATE OR REPLACE VIEW dw.vw_kpi_general AS
SELECT COUNT(*)                                                  AS total_comentarios,
       ROUND(AVG(puntaje), 2)                                    AS promedio_satisfaccion,
       SUM(es_positiva)                                          AS positivas,
       SUM(es_neutra)                                            AS neutras,
       SUM(es_negativa)                                          AS negativas,
       ROUND(100.0 * SUM(es_positiva) / NULLIF(COUNT(*), 0), 1) AS pct_positivas,
       ROUND(100.0 * SUM(es_neutra)   / NULLIF(COUNT(*), 0), 1) AS pct_neutras,
       ROUND(100.0 * SUM(es_negativa) / NULLIF(COUNT(*), 0), 1) AS pct_negativas
FROM dw.fact_opinion;

-- Por fuente y canal (1.3, sección 6)
CREATE OR REPLACE VIEW dw.vw_por_fuente AS
SELECT f.tipo_fuente,
       f.canal,
       COUNT(*)                                                  AS total_comentarios,
       ROUND(AVG(o.puntaje), 2)                                  AS puntaje_promedio,
       SUM(o.es_positiva)                                        AS positivas,
       SUM(o.es_neutra)                                          AS neutras,
       SUM(o.es_negativa)                                        AS negativas,
       ROUND(100.0 * SUM(o.es_positiva) / COUNT(*), 1)           AS pct_positivas,
       ROUND(100.0 * SUM(o.es_negativa) / COUNT(*), 1)           AS pct_negativas
FROM dw.fact_opinion o
JOIN dw.dim_fuente f ON f.sk_fuente = o.sk_fuente
GROUP BY f.tipo_fuente, f.canal;

-- Resumen por producto (sección 2)
CREATE OR REPLACE VIEW dw.vw_producto_resumen AS
SELECT p.sk_producto,
       p.id_producto,
       p.nombre                                                  AS producto,
       p.categoria,
       COUNT(*)                                                  AS total_comentarios,
       ROUND(AVG(o.puntaje), 2)                                  AS puntaje_promedio,
       SUM(o.es_positiva)                                        AS positivas,
       SUM(o.es_neutra)                                          AS neutras,
       SUM(o.es_negativa)                                        AS negativas,
       ROUND(100.0 * SUM(o.es_positiva) / COUNT(*), 1)           AS pct_satisfaccion
FROM dw.fact_opinion o
JOIN dw.dim_producto p ON p.sk_producto = o.sk_producto
GROUP BY p.sk_producto, p.id_producto, p.nombre, p.categoria;

-- Evolución mensual de cada producto (2.4)
CREATE OR REPLACE VIEW dw.vw_producto_mensual AS
SELECT p.nombre                                                  AS producto,
       t.anio_mes,
       COUNT(*)                                                  AS total_comentarios,
       ROUND(AVG(o.puntaje), 2)                                  AS puntaje_promedio,
       ROUND(100.0 * SUM(o.es_positiva) / COUNT(*), 1)           AS pct_satisfaccion
FROM dw.fact_opinion o
JOIN dw.dim_producto p ON p.sk_producto = o.sk_producto
JOIN dw.dim_tiempo t   ON t.id_tiempo = o.id_tiempo
GROUP BY p.nombre, t.anio_mes;

-- Tendencia mensual (sección 4)
CREATE OR REPLACE VIEW dw.vw_tendencia_mensual AS
SELECT t.anio,
       t.mes,
       t.anio_mes,
       COUNT(*)                                                  AS total_comentarios,
       ROUND(AVG(o.puntaje), 2)                                  AS puntaje_promedio,
       ROUND(100.0 * SUM(o.es_positiva) / COUNT(*), 1)           AS pct_positivas,
       ROUND(100.0 * SUM(o.es_neutra)   / COUNT(*), 1)           AS pct_neutras,
       ROUND(100.0 * SUM(o.es_negativa) / COUNT(*), 1)           AS pct_negativas
FROM dw.fact_opinion o
JOIN dw.dim_tiempo t ON t.id_tiempo = o.id_tiempo
GROUP BY t.anio, t.mes, t.anio_mes;

-- Tendencia trimestral (4.1)
CREATE OR REPLACE VIEW dw.vw_tendencia_trimestral AS
SELECT t.anio,
       t.trimestre,
       t.anio_trimestre,
       COUNT(*)                                                  AS total_comentarios,
       ROUND(AVG(o.puntaje), 2)                                  AS puntaje_promedio,
       ROUND(100.0 * SUM(o.es_positiva) / COUNT(*), 1)           AS pct_positivas,
       ROUND(100.0 * SUM(o.es_negativa) / COUNT(*), 1)           AS pct_negativas
FROM dw.fact_opinion o
JOIN dw.dim_tiempo t ON t.id_tiempo = o.id_tiempo
GROUP BY t.anio, t.trimestre, t.anio_trimestre;

-- Actividad por cliente (3.1); excluye los comentarios anónimos
CREATE OR REPLACE VIEW dw.vw_cliente_actividad AS
SELECT c.sk_cliente,
       c.id_cliente,
       c.nombre                                                  AS cliente,
       COUNT(*)                                                  AS total_opiniones,
       ROUND(AVG(o.puntaje), 2)                                  AS puntaje_promedio,
       SUM(o.es_positiva)                                        AS positivas,
       SUM(o.es_negativa)                                        AS negativas
FROM dw.fact_opinion o
JOIN dw.dim_cliente c ON c.sk_cliente = o.sk_cliente
WHERE o.sk_cliente <> 0
GROUP BY c.sk_cliente, c.id_cliente, c.nombre;

-- Segmentos de clientes (3.2, 3.3): hoy todo es "No disponible" porque los CSV no traen esos datos
CREATE OR REPLACE VIEW dw.vw_segmento_cliente AS
SELECT c.pais,
       c.rango_edad,
       c.tipo_cliente,
       COUNT(*)                                                  AS total_opiniones,
       ROUND(AVG(o.puntaje), 2)                                  AS puntaje_promedio,
       ROUND(100.0 * SUM(o.es_positiva) / COUNT(*), 1)           AS pct_positivas
FROM dw.fact_opinion o
JOIN dw.dim_cliente c ON c.sk_cliente = o.sk_cliente
WHERE o.sk_cliente <> 0
GROUP BY c.pais, c.rango_edad, c.tipo_cliente;

-- Comentarios por evento o campaña (4.2); sin eventos registrados todo cae en "Sin evento"
CREATE OR REPLACE VIEW dw.vw_evento_resumen AS
SELECT e.nombre                                                  AS evento,
       e.tipo,
       COUNT(*)                                                  AS total_comentarios,
       ROUND(AVG(o.puntaje), 2)                                  AS puntaje_promedio,
       ROUND(100.0 * SUM(o.es_positiva) / COUNT(*), 1)           AS pct_positivas
FROM dw.fact_opinion o
JOIN dw.dim_evento e ON e.sk_evento = o.sk_evento
GROUP BY e.nombre, e.tipo;
